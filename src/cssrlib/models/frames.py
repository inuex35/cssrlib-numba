def Rx(t):
    ct, st = cos(t), sin(t)
    return np.array([[1.0, 0.0, 0.0], [0.0, ct, st], [0.0, -st, ct]])


def Ry(t):
    ct, st = cos(t), sin(t)
    return np.array([[ct, 0.0, -st], [0.0, 1.0, 0.0], [st, 0.0, ct]])


def Rz(t):
    ct, st = cos(t), sin(t)
    return np.array([[ct, st, 0.0], [-st, ct, 0.0], [0.0, 0.0, 1.0]])


